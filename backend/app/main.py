# --------------------------------------------------------------------------
# forecast
# --------------------------------------------------------------------------
@app.get("/api/forecast/load", tags=["forecast"])
def forecast_load(horizon: int = 1):
    if horizon not in (1, 6, 12, 24):
        raise HTTPException(400, "horizon must be one of 1, 6, 12, 24")
    errs = engine.forecast_errors[horizon]
    mae = sum(e["abs"] for e in errs) / len(errs) if errs else None
    rmse = (sum(e["sq"] for e in errs) / len(errs)) ** 0.5 if errs else None
    return {
        "horizon_h": horizon, "mae_kw": round(mae, 1) if mae is not None else None,
        "rmse_kw": round(rmse, 1) if rmse is not None else None,
        "samples_scored": len(errs),
        "points": engine.forecast_points[horizon][-48:],
    }


@app.get("/api/forecast/renewables", tags=["forecast"])
def forecast_renewables(horizon: int = 1):
    if horizon not in (1, 6, 12, 24):
        raise HTTPException(400, "horizon must be one of 1, 6, 12, 24")
    return {"horizon_h": horizon, "points": engine.forecast_points[horizon][-48:]}


