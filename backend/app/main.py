# --------------------------------------------------------------------------
# sync / offline
# --------------------------------------------------------------------------
@app.get("/api/sync/status", tags=["sync"])
def sync_status():
    return {
        "online": engine.online, "syncing": engine.syncing, "outbox": engine.outbox,
        "log": engine.sync_log[:20],
    }


@app.post("/api/sync", tags=["sync"])
def sync_now():
    if not engine.online:
        raise HTTPException(409, "cannot sync while offline; call /api/simulation/online first")
    engine.sync_step()
    return sync_status()


# --------------------------------------------------------------------------
# simulation control
# --------------------------------------------------------------------------
@app.post("/api/simulation/start", tags=["simulation"])
def sim_start():
    engine.running = True
    return {"running": engine.running}


@app.post("/api/simulation/pause", tags=["simulation"])
def sim_pause():
    engine.running = False
    return {"running": engine.running}


@app.post("/api/simulation/reset", tags=["simulation"])
def sim_reset():
    engine.reset()
    for _ in range(8):
        engine.tick()
    return {"reset": True, "sim_time": engine.sim_time.isoformat()}


@app.post("/api/simulation/offline", tags=["simulation"])
def sim_offline():
    engine.set_online(False)
    return sync_status()


@app.post("/api/simulation/online", tags=["simulation"])
def sim_online():
    engine.set_online(True)
    return sync_status()


@app.post("/api/simulation/speed", tags=["simulation"])
def sim_speed(body: SpeedBody):
    engine.speed = body.speed
    return {"speed": engine.speed}


@app.post("/api/simulation/scenario", tags=["simulation"])
def sim_scenario(body: ScenarioBody):
    if body.id not in SCENARIO_IDS:
        raise HTTPException(400, f"unknown scenario id '{body.id}'. Valid ids: {sorted(SCENARIO_IDS)}")
    engine.apply_scenario(body.id)
    return {"scenario": engine.scenario or "normal"}
