"""
POLAR-EMS backend API.

Run locally with:
    uvicorn app.main:app --reload --port 8000

Then open http://127.0.0.1:8000/docs for interactive Swagger docs, or run
../cli.py in a second terminal for a menu-driven text interface.

This backend is a synthetic simulation (see engine.py's module docstring
and README.md) -- there is no connection to real station hardware.
"""

from __future__ import annotations

import asyncio
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from .engine import SCENARIOS, SCENARIO_IDS, SimulationEngine

engine = SimulationEngine()
_tick_task: Optional[asyncio.Task] = None
TICK_INTERVAL_SECONDS = 1.0


async def _tick_loop():
    while True:
        try:
            engine.tick()
        except Exception as exc:  # never let a bad tick kill the loop
            print(f"[tick error] {exc!r}")
        await asyncio.sleep(TICK_INTERVAL_SECONDS)


@asynccontextmanager
async def lifespan(app: FastAPI):
    global _tick_task
    _tick_task = asyncio.create_task(_tick_loop())
    print("POLAR-EMS backend started. Simulation clock ticking every "
          f"{TICK_INTERVAL_SECONDS}s of real time.")
    yield
    if _tick_task:
        _tick_task.cancel()


app = FastAPI(
    title="POLAR-EMS API",
    description=(
        "Synthetic microgrid simulation for an isolated polar research station. "
        "Weather, generation, load, battery, diesel and dispatch are computed by an "
        "explicit physical/rules model running on this server -- see /health and README.md."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # dev-friendly default; restrict to your deployed frontend origin(s) in production
    allow_credentials=False,
    allow_methods=["*"],
    allow_headers=["*"],
)


# --------------------------------------------------------------------------
# request bodies
# --------------------------------------------------------------------------
class SpeedBody(BaseModel):
    speed: int = Field(..., ge=1, le=20, description="Simulated hours per tick multiplier (1, 4, or 12 in the UI)")


class ScenarioBody(BaseModel):
    id: str = Field(..., description="One of: " + ", ".join(sorted(SCENARIO_IDS)))


# --------------------------------------------------------------------------
# health / meta
# --------------------------------------------------------------------------
@app.get("/health", tags=["meta"])
def health():
    return {"status": "ok", "simulated": True, "sim_time": engine.sim_time.isoformat()}


